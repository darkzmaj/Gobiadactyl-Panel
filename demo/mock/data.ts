// Every value here is invented for the demo. Hosts use reserved example names and addresses come from the
// documentation ranges (RFC 5737), so nothing points at a real machine.
export type PowerState = 'running' | 'offline' | 'starting' | 'stopping';

export interface Allocation {
    id: number;
    ip: string;
    ip_alias: string | null;
    port: number;
    notes: string | null;
    is_default: boolean;
}

export interface Variable {
    name: string;
    description: string;
    env_variable: string;
    default_value: string;
    server_value: string | null;
    is_editable: boolean;
    rules: string;
}

export interface DemoServer {
    internalId: number;
    uuid: string;
    identifier: string;
    name: string;
    description: string;
    owner: boolean;
    ownerName: string;
    node: number;
    egg: { id: number; uuid: string; name: string };
    image: string;
    images: Record<string, string>;
    rawStartup: string;
    limits: { memory: number; swap: number; disk: number; io: number; cpu: number; threads: string | null; oom_disabled: boolean };
    allocations: Allocation[];
    variables: Variable[];
    color: string | null;
    categories: number[];
    state: PowerState;
    startedAt: number;
    /** Typical load while running: a share of the CPU limit, of the memory limit, and disk use in MiB. */
    load: { cpu: number; memory: number; disk: number };
    kind: 'paper' | 'velocity' | 'fabric' | 'node' | 'rust';
    files: Folder;
}

export interface FileNode {
    name: string;
    content?: string;
    children?: Folder;
    modified: string;
    size?: number;
}
export type Folder = Map<string, FileNode>;

