/** What a running server reports right now: steady numbers with a little movement. */
export function usage(server: DemoServer) {
    const running = server.state === 'running';
    const wave = (period: number, offset: number) => Math.sin(Date.now() / period + offset + server.internalId);
    const cpu = running ? Math.max(0.5, server.load.cpu * server.limits.cpu * (1 + 0.12 * wave(2300, 0))) : 0;
    const memory = running ? Math.round(server.load.memory * server.limits.memory * 1048576 * (1 + 0.015 * wave(5100, 1))) : 0;
    return {
        cpu_absolute: Math.round(cpu * 100) / 100,
        memory_bytes: memory,
        memory_limit_bytes: server.limits.memory * 1048576,
        disk_bytes: server.load.disk * 1048576,
        network: { rx_bytes: running ? Math.round((Date.now() - server.startedAt) * 4.1) : 0, tx_bytes: running ? Math.round((Date.now() - server.startedAt) * 9.7) : 0 },
        uptime: running ? Date.now() - server.startedAt : 0,
        state: server.state,
    };
}
