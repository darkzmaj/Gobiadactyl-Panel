const now = Date.now();
const iso = (minutesAgo: number) => new Date(now - minutesAgo * 60_000).toISOString();

const file = (name: string, content: string, minutesAgo = 600): [string, FileNode] => [name, { name, content, modified: iso(minutesAgo) }];
const folder = (name: string, entries: [string, FileNode][], minutesAgo = 900): [string, FileNode] => [name, { name, children: new Map(entries), modified: iso(minutesAgo) }];
// A binary file: listed with its size, never opened as text.
const blob = (name: string, size: number, minutesAgo = 2000): [string, FileNode] => [name, { name, size, modified: iso(minutesAgo) }];

